#!/usr/bin/env node
/**
 * check-module-counts — the guard against "65 of PrimeNG's 117 modules" written in forty places.
 *
 * WHY THIS EXISTS: this project's central claim is a number. It ships a warranted subset of
 * PrimeNG's modules and says so — in the README, in PROVENANCE, in SUPPORT and TRIAGE, in five
 * issue templates, in two workflow comments, in the MCP server's tool descriptions that go out
 * over the wire, and in the showcase source. The number is the offer. It is also, in every one
 * of those places, a bare string that nothing reads.
 *
 * Promoting `iftalabel` out of `attic/` on 2026-08-31 moved the closure from 64 to 65 and the
 * attic from 53 to 52. That single move made **34 sentences wrong at once**, and `npm run check`
 * stayed green at 17/17 through all of it, because no gate looked at prose.
 *
 * Two of those sentences deserve their own mention, because they show the drift runs BOTH ways:
 * `apps/showcase/src/app.ts` and `data.ts` said "the 65 pages" and "all 65 routes" while the
 * real count was 64. They had been wrong for weeks, nobody noticed, and the promotion made them
 * correct BY ACCIDENT. A number that becomes right on its own is the same defect as one that
 * becomes wrong on its own — neither was ever being checked.
 *
 * So the counts are DERIVED here, from the closure the build actually warrants and the
 * directories the attic actually holds, and every documented copy is checked against them.
 *
 * ---
 *
 * WHAT THIS GATE DELIBERATELY DOES NOT DO, and why:
 *
 * 1. It does not check the module-count ASSERTIONS in the test suites. `npm run test:tools`
 *    already fails on those — eight of them broke during the same promotion and the suite
 *    caught every one. A second gate over the same lines would only teach people that two
 *    things must be updated where one already suffices. It DOES check the prose COMMENTS in
 *    those same files, because nothing reads a comment.
 *
 * 2. It does not accept spelled-out numbers, unlike check-gate-count. These counts are all
 *    past twenty, which is where that gate's word list stops on purpose. Refusing words here
 *    also sidesteps the trap check-gate-count records at its own site list: in an alternation,
 *    `eight` matches happily INSIDE `eighteen` unless a literal suffix forces the backtrack.
 *
 * 3. It does not guard DERIVED figures — a count the reader could compute from another count.
 *    Two existed and both were wrong after the promotion: README said "and 47 others" (the
 *    attic minus the six modules it names by hand) and CONTRIBUTING said "Twelve of the 52"
 *    (generated by seed-attic-issues.mjs, which had moved to 11 because `iftalabel` was one of
 *    the twelve). Neither is findable by searching for the old number. Following the precedent
 *    check-gate-count set when it deleted "the other five" rather than guarding it, both
 *    sentences were rewritten to drop the figure. If you are about to add a number that is
 *    another number minus something, delete it instead of adding a site for it.
 *
 * Usage: node tools/check-module-counts.mjs
 */

import { readdirSync, readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { site, auditSite, auditTable } from './module-counts-lib.mjs';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(resolve(repoRoot, f), 'utf8');
const dirs = (d) =>
    readdirSync(resolve(repoRoot, d), { withFileTypes: true })
        .filter((e) => e.isDirectory())
        .map((e) => e.name)
        .sort();

/**
 * The authoritative sources. SHIPPED comes from the closure file the build warrants and
 * `check:scope` already holds to the source tree; ATTIC is counted off the filesystem.
 *
 * TOTAL is derived rather than hardcoded to 117. That is deliberate: 117 is a fact about
 * upstream PrimeNG 21.1.9, and the only reason we may still claim it is that every module is
 * either shipped or kept in the attic. Delete an attic module instead of promoting it and the
 * sum stops being 117 — which is exactly when every "of 117" sentence in the repository
 * quietly becomes a false claim about someone else's software.
 */
const SHIPPED = JSON.parse(read('tools/scope/closure.json')).closure.length;
const ATTIC_MODULES = dirs('packages/angulux/attic');
const ATTIC = ATTIC_MODULES.length;
const TOTAL = SHIPPED + ATTIC;

const FACTS = { shipped: SHIPPED, attic: ATTIC, total: TOTAL };

// `site`, `auditSite` and `auditTable` live in module-counts-lib.mjs so they can be tested
// against fixture strings instead of against this repository — see tools/test/.

/**
 * Every place a count is written down, which count it is, and how to read it back out.
 *
 * A site whose text stops matching is itself a failure. Rewording a sentence until this gate
 * can no longer find it is the same outcome as deleting the gate, so it is reported the same
 * way — the count has to stay mechanically checkable, not merely happen to be right today.
 */
const SITES = [
    // ── the offer, as told to anyone opening an issue ──
    ['.github/ISSUE_TEMPLATE/bug_report.yml', site('%N% modules sit unbuilt'), 'attic'],
    ['.github/ISSUE_TEMPLATE/config.yml', site("ships %N% of PrimeNG's \\d+ modules"), 'shipped'],
    ['.github/ISSUE_TEMPLATE/config.yml', site("ships \\d+ of PrimeNG's %N% modules"), 'total'],
    ['.github/ISSUE_TEMPLATE/config.yml', site('The other %N% are carried'), 'attic'],
    ['.github/ISSUE_TEMPLATE/feature_request.yml', site('%N% modules are already in the repository'), 'attic'],
    ['.github/ISSUE_TEMPLATE/module_promotion.yml', site('one of the %N% unported modules'), 'attic'],
    ['.github/ISSUE_TEMPLATE/module_promotion.yml', site("\\*\\*%N% of PrimeNG's \\d+ modules\\*\\*"), 'shipped'],
    ['.github/ISSUE_TEMPLATE/module_promotion.yml', site("\\*\\*\\d+ of PrimeNG's %N% modules\\*\\*"), 'total'],
    ['.github/ISSUE_TEMPLATE/module_promotion.yml', site('The other %N% are carried'), 'attic'],
    ['.github/ISSUE_TEMPLATE/module_promotion.yml', site('"%N% modules with a warranty"'), 'shipped'],
    ['.github/ISSUE_TEMPLATE/module_promotion.yml', site('"%N% modules nobody checks"'), 'total'],

    // ── the two workflow comments that justify excluding attic/ from scanning ──
    ['.github/codeql/codeql-config.yml', site('attic/ holds %N% modules'), 'attic'],
    ['.github/workflows/codeql.yml', site('those %N% modules are verbatim'), 'attic'],
    ['.github/workflows/triage.yml', site('one of the %N% modules'), 'attic'],

    // ── the documents a reader decides on ──
    ['CONTRIBUTING.md', site('The %N% unported modules'), 'attic'],
    ['CONTRIBUTING.md', site('is the same %N% sorted'), 'attic'],
    ['PROVENANCE.md', site('the %N% modules in the transitive closure'), 'shipped'],
    ['PROVENANCE.md', site('\\| %N% modules outside the closure'), 'attic'],
    ['PROVENANCE.md', site('drifting from the agreed %N% modules'), 'shipped'],
    ['README.md', site("It ships %N% of PrimeNG's \\d+ modules"), 'shipped'],
    ['README.md', site("It ships \\d+ of PrimeNG's %N% modules"), 'total'],
    ['README.md', site('all %N% are listed in'), 'attic'],
    ['README.md', site('drifting off the %N% warranted modules'), 'shipped'],
    ['README.md', site('### 3\\. %N% warranted modules instead of \\d+'), 'shipped'],
    ['README.md', site('### 3\\. \\d+ warranted modules instead of %N%'), 'total'],
    ['README.md', site('The other %N% live in'), 'attic'],
    ['README.md', site('%N% of \\d+ modules\\. Missing'), 'shipped'],
    ['README.md', site('\\d+ of %N% modules\\. Missing'), 'total'],
    ['README.md', site('for all %N% modules generated'), 'shipped'],
    ['SUPPORT.md', site("%N% of PrimeNG's modules are carried"), 'attic'],
    ['TRIAGE.md', site('one of the %N% unbuilt modules'), 'attic'],

    // ── the generated cost table. Regenerate it with tools/community/survey-attic.mjs. ──
    ['docs/attic-promotion.md', site("ships \\*\\*%N%\\*\\* of PrimeNG's \\d+ modules"), 'shipped'],
    ['docs/attic-promotion.md', site("ships \\*\\*\\d+\\*\\* of PrimeNG's %N% modules"), 'total'],
    ['docs/attic-promotion.md', site('The other \\*\\*%N%\\*\\* are inherited'), 'attic'],
    ['docs/attic-promotion.md', site('## All %N%, cheapest first'), 'attic'],
    ['docs/attic-promotion.md', site('\\*\\*\\d+ of %N%\\*\\* drag nothing'), 'attic'],

    // ── the showcase. app.ts and data.ts are the pair that were wrong for weeks. ──
    ['apps/showcase/src/app.routes.ts', site('One route for all %N% modules'), 'shipped'],
    ['apps/showcase/src/app.ts', site('every one of the %N% pages'), 'shipped'],
    ['apps/showcase/src/data.ts', site('spans all %N% routes'), 'shipped'],
    ['apps/showcase/src/pages/module-page.ts', site('all %N% modules\\. The demo half'), 'shipped'],

    // ── the MCP server. These strings LEAVE the repository: they are tool descriptions an
    //    agent reads, so a stale count here is published on our behalf, not merely written down.
    ['packages/angulux-mcp/README.md', site('all %N% for a fraction of what one large module costs'), 'shipped'],
    ['packages/angulux-mcp/README.md', site('\\*\\*Only the %N% warranted modules\\.\\*\\*'), 'shipped'],
    ['packages/angulux-mcp/README.md', site('The other %N% live in the repository'), 'attic'],
    ['packages/angulux-mcp/src/tools.mjs', site('this returns all %N% modules for a fraction'), 'shipped'],
    ['packages/angulux-mcp/src/tools.mjs', site('it returns all %N% for less than one large'), 'shipped'],

    // ── prose inside tooling and tests. The ASSERTIONS beside these are test:tools' job; the
    //    comments are nobody's, which is the only reason they are listed here.
    ['tools/check-demo-code.mjs', site('%N% unported modules kept verbatim'), 'attic'],
    ['tools/community/seed-attic-issues.mjs', site('The %N% modules only become contributable'), 'attic'],
    ['tools/corpus/test/generate.test.mjs', site('// %N% attic modules must not appear'), 'attic'],
    ['tools/corpus/test/module.test.mjs', site('it describes all %N% modules'), 'shipped'],
    ['tools/corpus/test/module.test.mjs', site('declares, across all %N%'), 'shipped'],
    ['tools/corpus/test/site.test.mjs', site('The %N% out-of-scope modules'), 'attic'],
    ['tools/corpus/test/site.test.mjs', site('// \\d+ - %N% = \\d+ unported'), 'shipped'],
    ['tools/corpus/test/site.test.mjs', site('// \\d+ - \\d+ = %N% unported'), 'attic'],
    ['tools/corpus/test/site.test.mjs', site('The project ships %N% of \\d+ modules'), 'shipped'],
    ['tools/corpus/test/site.test.mjs', site('The project ships \\d+ of %N% modules'), 'total']
];

const problems = [];
for (const [file, rx, fact] of SITES) {
    const expected = FACTS[fact];
    let text;
    try {
        text = read(file);
    } catch {
        problems.push([file, `file not found — a module-count site moved or was deleted`]);
        continue;
    }
    for (const msg of auditSite(text, rx, expected, fact)) problems.push([file, msg]);
}

/**
 * The stronger question, and the one counting cannot ask: does the cost table list the modules
 * the attic actually holds? A promoted module left in that table sends the next contributor to
 * pick something already shipped, and every count on the page can be right while it happens.
 */
const TABLE_ROW = /^\|\s*`([a-z0-9-]+)`\s*\|/gm;
const tabled = [...read('docs/attic-promotion.md').matchAll(TABLE_ROW)].map((m) => m[1]).sort();

for (const msg of auditTable(ATTIC_MODULES, tabled)) problems.push(['docs/attic-promotion.md', msg]);

if (problems.length) {
    console.error(`\n✗ the documented module counts are out of sync\n`);
    console.error(`  shipped ${SHIPPED} · attic ${ATTIC} · upstream total ${TOTAL}\n`);
    let last = null;
    for (const [file, msg] of problems) {
        if (file !== last) {
            console.error(`  ${file}`);
            last = file;
        }
        console.error(`      ${msg}`);
    }
    console.error(
        `\n  Fix each, and regenerate the cost table with \`node tools/community/survey-attic.mjs\`.\n` +
            `  If a figure here is one the reader could compute from another, delete it instead.\n`
    );
    process.exit(1);
}

console.log(
    `✓ check-module-counts: all ${SITES.length} documented sites agree — ${SHIPPED} shipped, ` +
        `${ATTIC} in attic, ${TOTAL} upstream — and the cost table lists exactly the ${ATTIC} attic module(s).`
);
