// The icon stylesheet the site ships: primeicons.css with its font sources cut down to the
// one format a supported browser uses.
//
// The package declares five, led by `.eot` for Internet Explorer. Measured on the production
// build (`npm run measure:load`), Chromium fetched the 85 kB `.eot` on EVERY page next to the
// 35 kB `.woff2` it rendered with — 28 % of a median page. Declaring a second @font-face after
// the package's does not help: that was tried and measured, and both files were still fetched.
// The first rule has to not exist, so the stylesheet is rewritten rather than overridden.
//
// Everything else — the 300-odd `.pi-*` rules — is copied through untouched, from the pinned
// package, on every build. Nothing here is a fork of it.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = readFileSync(join(app, 'node_modules/primeicons/primeicons.css'), 'utf8');

const FACE = /@font-face\s*\{[^}]*\}/g;
const faces = source.match(FACE) ?? [];

// One rule, naming the woff2: anything else means the package changed shape, and a silent
// pass-through would put the `.eot` back without a single red line.
if (faces.length !== 1 || !faces[0].includes("url('./fonts/primeicons.woff2')")) {
    console.error(`build-icons: expected exactly one @font-face naming ./fonts/primeicons.woff2 in primeicons.css, found ${faces.length}`);
    process.exit(1);
}

const face = `@font-face {
    font-family: 'primeicons';
    font-display: block;
    src: url('../../node_modules/primeicons/fonts/primeicons.woff2') format('woff2');
    font-weight: normal;
    font-style: normal;
}`;

const out = join(app, 'src/generated/primeicons.css');
const rules = (source.match(/\.pi-[\w-]+:before/g) ?? []).length;

if (rules < 100) {
    console.error(`build-icons: only ${rules} icon rules found in primeicons.css — refusing to write a stylesheet with no icons in it`);
    process.exit(1);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `/* Generated by scripts/build-icons.mjs from primeicons.css. Do not edit. */\n${source.replace(FACE, face)}`);
console.log(`build-icons: ${rules} icon rules, one font source (woff2)`);
